def fail(msg):
    sys.exit(f"build_pages: {msg}")


def esc(s):
    """Same escaping as esc() in assets/js/attacks.js, so the static rows match the rendered ones."""
    return re.sub(r"[&<>\"']", lambda m: {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"}[m.group(0)], str(s))


def plain(fragment):
    """Text of an HTML fragment (tags removed, entities decoded)."""
    return html.unescape(re.sub(r"<[^>]+>", "", fragment))


def one(pattern, text, what, optional=False):
    m = re.search(pattern, text, re.S)
    if not m:
        if optional:
            return None
        fail(f"{what} not found")
    return m.group(1)


def page_name(slug):
    return slug.replace("_", "-") + ".html"


# Sources ---------------------------------------------------------------------------------------------

CARD = re.compile(
    r'<article class="card atk-card family-card family-card--(?P<fam>[a-z]+)" id="attack-(?P<slug>[a-z_-]+)" '
    r'data-family="(?P=fam)" aria-labelledby="attack-(?P<n>\d+)">\n(?P<body>.*?)\n</article>', re.S)
FAMILY = re.compile(
    r'<section class="section atk-family" data-family="(?P<fam>[a-z]+)" aria-labelledby="family-(?P=fam)">'
    r'.*?<span class="atk-family__meta">(?P<meta>.*?)</span>.*?<h2 id="family-(?P=fam)">(?P<title>.*?)</h2>'
    r'\s*<p class="lede">(?P<lede>.*?)</p>', re.S)


def read_cards(src):
    cards = []
    for m in CARD.finditer(src):
        b, slug, n = m.group("body"), m.group("slug"), int(m.group("n"))
        what = f"attack {n} ({slug}):"
        link = re.search(r'<span class="atk-card__name"><a href="attack/([^"]+)">(.*?)</a></span>', b)
        if not link:
            fail(f"{what} the card title does not link to its page")
        if link.group(1) != page_name(slug):
            fail(f"{what} the card links to attack/{link.group(1)}, expected attack/{page_name(slug)}")
        if f'href="attack/{page_name(slug)}">Attack page' not in b:
            fail(f"{what} the links row of the card has no 'Attack page' link")
        dl = one(r'<dl class="atk-dl">\n(.*?)\n\s*</dl>', b, f"{what} placement and goal")
        cards.append({
            "n": n, "slug": slug, "fam": m.group("fam"), "page": page_name(slug),
            "name": link.group(2),
            "tags": one(r'<p class="atk-card__tags">(.*?)</p>', b, f"{what} tags"),
            "desc": one(r'<p class="atk-card__desc">(.*?)</p>', b, f"{what} description"),
            "dl": re.findall(r"<div><dt>(.*?)</dt><dd>(.*?)</dd></div>", dl),
            "excerpt": one(r"</dl>\n(.*?)\n\s*</details>", b, f"{what} excerpt"),
            "results": one(r'data-attack-results="%d">(.*?)</div>\n' % n, b, f"{what} results"),
            "note": one(r'<p class="atk-results__note">(.*?)</p>', b, "", optional=True),
            "extra": one(r'\n  (<div class="atk-card__extra.*?)\n  <p class="atk-card__links">', b, "", optional=True),
            "kind": one(r"<code>--attacks ([a-z_]+)</code>", b, "", optional=True),
            "example": one(r'href="(https://github\.com/[^"]+/example/[^"]+)"', b, "", optional=True),
            "doc": one(r'href="(https://github\.com/[^"]+/docs/ATTACKS\.md[^"]*)"', b, f"{what} documentation link"),
        })
    if [c["n"] for c in cards] != list(range(1, len(cards) + 1)):
        fail("the attack cards of attacks.html are not numbered 1, 2, 3 ... in page order")
    return cards


def read_families(src):
    fams = {}
    for m in FAMILY.finditer(src):
        meta = re.sub(r"^Rows [0-9]+–[0-9]+ · ", "", m.group("meta"))
        fams[m.group("fam")] = {"meta": meta, "title": m.group("title"), "lede": m.group("lede")}
    return fams


def read_chrome(template, sub_page):
    """Header and footer of the template. For a page in attack/ (sub_page), links go one level up and the
    Attacks item of the menu is marked as the current section."""
    header = one(r"(  <header class=\"site-header\">.*?</header>)", template, "the header of the template")
    footer = one(r"(  <footer class=\"site-footer\">.*?</html>)", template, "the footer of the template")
    theme = one(r"(  <script>\(function\(\)\{var d=document\.documentElement.*?</script>)", template, "the theme script")
    header = re.sub(r"\n\s*<!-- (?:CHANGE|\"Help us\").*?-->", "", header)
    if not sub_page:
        return theme, header, footer
    up = lambda s:re.sub(r'\b(href|src)="(?!https?:|mailto:|#|/|data:|\.\./)([^"]+)"', r'\1="../\2"', s)
    header, footer = up(header), up(footer)
    current = '<li><a href="../attacks.html">Attacks</a></li>'
    if header.count(current) != 1:
        fail("the Attacks item of the template header has changed")
    header = header.replace(current, '<li><a href="../attacks.html" aria-current="true">Attacks</a></li>')
    return theme, header, footer


