TODAY = datetime.date.today().isoformat()


def lastmod(rel):
    """Date of the last commit of a file, or today if it has uncommitted changes (or git is unavailable)."""
    try:
        dirty = subprocess.run(["git", "status", "--porcelain", "--", rel], cwd=ROOT, capture_output=True,
                               text=True, check=True).stdout.strip()
        if not dirty:
            date = subprocess.run(["git", "log", "-1", "--format=%cs", "--", rel], cwd=ROOT, capture_output=True,
                                  text=True, check=True).stdout.strip()
            if date:
                return date
    except (OSError, subprocess.CalledProcessError):
        pass
    return TODAY


def sitemap(attack_pages):
    roots = {p.name for p in ROOT.glob("*.html")} - NOT_IN_SITEMAP
    listed = {f for f, _, _ in SITE_PAGES}
    if roots != listed:
        fail("SITE_PAGES does not match the pages at the site root: "
             f"missing {sorted(roots - listed)}, unknown {sorted(listed - roots)}")
    rows = []
    for f, _, prio in SITE_PAGES:
        loc = SITE if f == "index.html" else SITE + f
        rows.append((loc, lastmod(f), prio))
    for f in attack_pages:
        rows.append((f"{SITE}{OUT_DIR}/{f}", lastmod(f"{OUT_DIR}/{f}"), ATTACK_PRIORITY))
    body = "\n".join(f"  <url><loc>{loc}</loc><lastmod>{mod}</lastmod><priority>{prio}</priority></url>"
                     for loc, mod, prio in rows)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "\n</urlset>\n")


def write(path, text):
    """Write with LF line ends, only when the content changes."""
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def main():
    src = (ROOT / "attacks.html").read_text(encoding="utf-8")
    data = json.loads((ROOT / "data" / "results.json").read_text(encoding="utf-8"))
    template = (ROOT / "tools" / "page_template.html").read_text(encoding="utf-8")
    chrome = read_chrome(template, sub_page=True)
    cards, fams = read_cards(src), read_families(src)
    models, by_id = data["models"], {a["id"]: a for a in data["attacks"]}
    if len(cards) != len(by_id):
        fail(f"{len(cards)} cards in attacks.html, {len(by_id)} attacks in data/results.json")
    if set(fams) != {f["key"] for f in data["families"]}:
        fail("the family sections of attacks.html do not match the families of data/results.json")
    for c in cards:
        a = by_id[c["n"]]
        if a["slug"] != c["slug"] or a["family"] != c["fam"]:
            fail(f"attack {c['n']}: the card ({c['slug']}, {c['fam']}) and the data ({a['slug']}, {a['family']}) differ")
        if c["results"] != results_html(a, models):
            fail(f"attack {c['n']} ({c['slug']}): the static results of the card differ from data/results.json")

    out = ROOT / OUT_DIR
    out.mkdir(exist_ok=True)
    changed, pages = 0, []
    for c in cards:
        text = build_page(c, cards, by_id[c["n"]], models, fams, data["families"], chrome, data["package"]["version"])
        changed += write(out / c["page"], text)
        pages.append(c["page"])
    for old in sorted(out.glob("*.html")):  # pages of attacks that no longer exist
        if old.name not in pages and GENERATED in old.read_text(encoding="utf-8")[:400]:
            old.unlink()
            print(f"removed {OUT_DIR}/{old.name}")
    smap = write(ROOT / SITEMAP_PAGE, build_sitemap_page(cards, fams, data["families"], read_chrome(template, sub_page=False)))
    sm = write(ROOT / "sitemap.xml", sitemap(pages))
    print(f"{len(pages)} attack pages in {OUT_DIR}/ ({changed} written); {SITEMAP_PAGE} "
          f"({'written' if smap else 'unchanged'}); sitemap.xml with {len(SITE_PAGES) + len(pages)} pages "
          f"({'written' if sm else 'unchanged'})")


if __name__ == "__main__":
    main()
