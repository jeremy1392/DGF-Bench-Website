# Site map page --------------------------------------------------------------------------------------

def page_outline(f):
    """Meta description and h2 sections (id, text) of a page. Headings that are visually hidden or carry
    no anchor (titles of widgets such as the leaderboard) are left out."""
    s = (ROOT / f).read_text(encoding="utf-8")
    desc = one(r'<meta name="description" content="([^"]*)"', s, f"the description of {f}")
    main = s[s.index("<main"):s.index("</main>")]
    sections = []
    for attrs, inner in re.findall(r"<h2(\s[^>]*)>(.*?)</h2>", main, re.S):
        sid = re.search(r'\bid="([^"]+)"', attrs)
        cls = re.search(r'\bclass="([^"]*)"', attrs)
        if sid and not (cls and re.search(r"\b(visually-hidden|no-anchor)\b", cls.group(1))):
            sections.append((sid.group(1), " ".join(plain(inner).split())))
    return html.unescape(desc), sections


