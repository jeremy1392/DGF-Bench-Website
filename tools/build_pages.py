def results_html(a, models):
    """Same markup as resultsHTML() in assets/js/attacks.js."""
    passed = []
    h = '<ul class="atk-res-list" role="list">'
    for m in models:
        c = a["cells"].get(m["id"])
        if not c:
            h += ('<li class="atk-res" data-state="na"><span class="atk-res__model">' + esc(m["name"]) +
                  '</span><span class="atk-res__value">n/a</span><span class="visually-hidden">, not applicable</span></li>')
            continue
        p = c["attributable"] > 0
        if p:
            passed.append(m["name"])
        h += ('<li class="atk-res" data-state="' + ("passed" if p else "blocked") + '"><span class="atk-res__model">' +
              esc(m["name"]) + '</span><span class="atk-res__value">' + f'{c["attributable"]}/{c["attacked"]}' +
              '</span><span class="visually-hidden">' + (", got through" if p else ", blocked") + "</span></li>")
    h += ('</ul><p class="atk-res-through"><strong>Got through:</strong> ' +
          (esc(", ".join(passed)) if passed else "none") + ".</p>")
    return h


def description(a):
    """Meta description: the mechanism of the attack from the data, at most about 160 characters."""
    d = a["mechanism"].strip()
    if len(d) > 160:
        d = d[:157].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    elif len(d) < 120:
        d += " September 2026 results on six AI models."
    return d


def facts(card, a, models):
    cells = [a["cells"][m["id"]] for m in models if a["cells"].get(m["id"])]  # null: cannot reach the model
    passed = sum(1 for c in cells if c["attributable"] > 0)
    applicable = len(cells)
    through = f"{passed} of {applicable} models" if passed else f"none of the {applicable} models"
    if applicable < len(models):
        through += " that can receive it"
    gates = sorted({c["attacked"] for c in cells})
    gates = str(gates[0]) if len(gates) == 1 else f"{gates[0]} to {gates[-1]}"
    rows = [
        ("Attack id", f"<code>{card['kind']}</code>" if card["kind"] else "none, not part of <code>dgf-bench run</code>"),
        ("In the DGF score", "yes" if a["in_score"] else "no"),
        ("Got through", through),
        ("September 2026 setup", f"{a['mode']}, {gates} attacked gates per model"),
    ]
    return "\n".join(f"          <div><dt>{t}</dt><dd>{d}</dd></div>" for t, d in rows)


