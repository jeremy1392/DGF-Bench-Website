    for c in siblings:
        num = f'<span class="atk-card__num"><span class="visually-hidden">Attack </span>{c["n"]}<span class="visually-hidden">:</span></span>'
        if c is card:
            items.append(f'<li><span class="atk-siblings__item" aria-current="page">{num} {c["name"]}</span></li>')
        else:
            items.append(f'<li><a class="atk-siblings__item" href="{c["page"]}">{num} {c["name"]}</a></li>')
    items = "\n          ".join(items)
    i = cards.index(card)
    prev_ = cards[i - 1] if i > 0 else None
    next_ = cards[i + 1] if i + 1 < len(cards) else None
