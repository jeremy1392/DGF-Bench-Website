    if prev_:
        pager.append(f'<a class="atk-pager__link atk-pager__link--prev" href="{prev_["page"]}" rel="prev">'
                     f'<span class="atk-pager__dir">Previous attack</span><span class="atk-pager__name">{prev_["n"]} · {prev_["name"]}</span></a>')
